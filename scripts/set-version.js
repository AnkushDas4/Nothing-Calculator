#!/usr/bin/env node
/**
 * scripts/set-version.js — keep the version in sync everywhere.
 *
 *   node scripts/set-version.js 3.1.0 [--code 30001] [--build 2026.10.11]
 *
 * Updates: package.json · js/version.js · android/app/build.gradle
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SEMVER = /^\d+\.\d+\.\d+/;
const VIRTUAL_HOST = 'ncalc.local';

function arg(name, fallback) {
  const index = process.argv.indexOf('--' + name);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

function versionCode(version) {
  const [major, minor, patch] = version.split(/[.\-+]/).map((part) => parseInt(part, 10) || 0);
  return major * 10000 + minor * 100 + patch;
}

function main() {
  const version = (process.argv[2] || '').trim();
  if (!SEMVER.test(version)) {
    console.error('usage: node scripts/set-version.js <major.minor.patch> [--code N] [--build STR]');
    process.exit(1);
  }
  const code = String(arg('code', versionCode(version)));
  const build = String(arg('build', new Date().toISOString().slice(0, 10)));

  // package.json
  const pkgPath = path.join(ROOT, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  pkg.version = version;
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');

  // js/version.js
  const versionPath = path.join(ROOT, 'js', 'version.js');
  fs.writeFileSync(
    versionPath,
    '/*!\n' +
      ' * N-Calc · version.js — generated by scripts/set-version.js\n' +
      ' * `version` is shown in the UI, `build` is stamped by CI.\n' +
      ' */\n' +
      "(function (root) {\n" +
      `  root.NC_VERSION = { version: '${version}', build: '${build}', date: '${build}' };\n` +
      "})(typeof self !== 'undefined' ? self : this);\n",
  );

  // android/app/build.gradle
  const gradlePath = path.join(ROOT, 'android', 'app', 'build.gradle');
  if (fs.existsSync(gradlePath)) {
    let gradle = fs.readFileSync(gradlePath, 'utf8');
    gradle = gradle.replace(/versionCode\s+\d+/, `versionCode ${code}`);
    gradle = gradle.replace(/versionName\s+"[^"]*"/, `versionName "${version}"`);
    fs.writeFileSync(gradlePath, gradle);
  }

  // android capacitor config (display name / id)
  const capPath = path.join(ROOT, 'android', 'app', 'src', 'main', 'assets', 'capacitor.config.json');
  if (fs.existsSync(capPath)) {
    const config = JSON.parse(fs.readFileSync(capPath, 'utf8'));
    fs.writeFileSync(
      capPath,
      JSON.stringify(
        {
          appId: config.appId || 'com.ankushdas.ncalc',
          appName: config.appName || 'n-calc',
          webDir: 'public',
          server: { androidScheme: 'https', hostname: VIRTUAL_HOST },
          android: { allowMixedContent: false, backgroundColor: '#0a0a0a' },
        },
        null,
        2,
      ) + '\n',
    );
  }

  console.log(`✔ version ${version} (code ${code}, build ${build})`);
}

main();
